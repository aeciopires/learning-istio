#!/usr/bin/env bash
# Creates the local kind cluster used for Istio practice/testing, mirroring
# INSTALL_REQUIREMENTS.md#kind (1 control-plane + 2 workers, MetalLB-ready
# port mappings). Idempotent: does nothing if the cluster already exists.
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

require_bin kind kubectl

if kind get clusters 2>/dev/null | grep -qx "$CLUSTER_NAME"; then
  log_info "kind cluster '$CLUSTER_NAME' already exists, skipping creation."
  exit 0
fi

log_step "Creating kind cluster '$CLUSTER_NAME' (node image: $KIND_NODE_IMAGE)"

KIND_CONFIG_FILE="$(mktemp -t kind-config-XXXXXX.yaml)"
trap 'rm -f "$KIND_CONFIG_FILE"' EXIT

cat >"$KIND_CONFIG_FILE" <<EOF
# Generated by agents/upgrade/scripts/create-cluster.sh - mirrors
# INSTALL_REQUIREMENTS.md#kind. Do not edit; re-run the script instead.
kind: Cluster
apiVersion: kind.x-k8s.io/v1alpha4
networking:
  podSubnet: "$POD_SUBNET"
  serviceSubnet: "$SERVICE_SUBNET"
nodes:
  - role: control-plane
    image: $KIND_NODE_IMAGE
    kubeadmConfigPatches:
    - |
      kind: InitConfiguration
      apiVersion: kubeadm.k8s.io/v1beta4
      nodeRegistration:
        kubeletExtraArgs:
          - name: nodeapp
            value: "loadbalancer"
    extraPortMappings:
    - containerPort: 80
      hostPort: 80
      listenAddress: "0.0.0.0"
      protocol: TCP
    - containerPort: 443
      hostPort: 443
      listenAddress: "0.0.0.0"
      protocol: TCP
  - role: worker
    image: $KIND_NODE_IMAGE
  - role: worker
    image: $KIND_NODE_IMAGE
EOF

kind create cluster --name "$CLUSTER_NAME" --config "$KIND_CONFIG_FILE"

log_info "Cluster '$CLUSTER_NAME' ready (context: kind-$CLUSTER_NAME)."
kubectl cluster-info --context "kind-$CLUSTER_NAME"
